export const auditLog = pgTable(
  "audit_log",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    actorId: text("actor_id").references(() => user.id, { onDelete: "set null" }),
    courseId: uuid("course_id").references(() => course.id, { onDelete: "cascade" }),
    action: varchar("action", { length: 64 }).notNull(),
    entityType: varchar("entity_type", { length: 32 }).notNull(),
    entityId: text("entity_id").notNull(),
    metadata: jsonb("metadata").$type<Record<string, unknown>>(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    index("audit_log_course_created_idx").on(t.courseId, t.createdAt),
    index("audit_log_entity_idx").on(t.entityType, t.entityId),
  ],
);

// ---------------------------------------------------------------------------
// Relations (for the Drizzle query API)
// ---------------------------------------------------------------------------

export const userRelations = relations(user, ({ many }) => ({
  sessions: many(session),
  accounts: many(account),
  memberships: many(courseMember),
}));

export const sessionRelations = relations(session, ({ one }) => ({
  user: one(user, { fields: [session.userId], references: [user.id] }),
}));

export const accountRelations = relations(account, ({ one }) => ({
  user: one(user, { fields: [account.userId], references: [user.id] }),
}));

export const courseRelations = relations(course, ({ one, many }) => ({
  creator: one(user, { fields: [course.createdBy], references: [user.id] }),
  members: many(courseMember),
  assignments: many(assignment),
}));

export const courseMemberRelations = relations(courseMember, ({ one }) => ({
  course: one(course, { fields: [courseMember.courseId], references: [course.id] }),
  user: one(user, { fields: [courseMember.userId], references: [user.id] }),
}));

export const assignmentRelations = relations(assignment, ({ one, many }) => ({
  course: one(course, { fields: [assignment.courseId], references: [course.id] }),
  criteria: many(rubricCriterion),
  submissions: many(submission),
}));

export const rubricCriterionRelations = relations(rubricCriterion, ({ one, many }) => ({
  assignment: one(assignment, {
    fields: [rubricCriterion.assignmentId],
    references: [assignment.id],
  }),
  levels: many(rubricLevel),
}));

export const rubricLevelRelations = relations(rubricLevel, ({ one }) => ({
  criterion: one(rubricCriterion, {
    fields: [rubricLevel.criterionId],
    references: [rubricCriterion.id],
  }),
}));

export const submissionRelations = relations(submission, ({ one, many }) => ({
  assignment: one(assignment, {
    fields: [submission.assignmentId],
    references: [assignment.id],
  }),
  student: one(user, { fields: [submission.studentId], references: [user.id] }),
  grade: one(grade),
  aiRuns: many(aiGradingRun),
}));

export const aiGradingRunRelations = relations(aiGradingRun, ({ one }) => ({
  submission: one(submission, {
    fields: [aiGradingRun.submissionId],
    references: [submission.id],
  }),
}));

export const gradeRelations = relations(grade, ({ one, many }) => ({
  submission: one(submission, { fields: [grade.submissionId], references: [submission.id] }),
  scores: many(criterionScore),
  regrade: one(regradeRequest),
}));

export const criterionScoreRelations = relations(criterionScore, ({ one }) => ({
  grade: one(grade, { fields: [criterionScore.gradeId], references: [grade.id] }),
  criterion: one(rubricCriterion, {
    fields: [criterionScore.criterionId],
    references: [rubricCriterion.id],
  }),
  level: one(rubricLevel, { fields: [criterionScore.levelId], references: [rubricLevel.id] }),
}));

export const regradeRequestRelations = relations(regradeRequest, ({ one }) => ({
  grade: one(grade, { fields: [regradeRequest.gradeId], references: [grade.id] }),
  student: one(user, { fields: [regradeRequest.studentId], references: [user.id] }),
}));
